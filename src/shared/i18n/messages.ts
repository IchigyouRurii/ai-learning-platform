const escapeRegExp = (value: string) =>
  value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

const compilePattern = (source: string) =>
  new RegExp(
    `^${source
      .split(/\{\d+\}/)
      .map(escapeRegExp)
      .join("(.+?)")}$`,
  );

const compiledPatterns = patternMessages.map(([english, chinese]) => ({
  english: compilePattern(english),
  chinese: compilePattern(chinese),
  enToZh: chinese,
  zhToEn: english,
}));

const captureMessages: Record<string, string> = {
  beginner: "入门",
  advanced: "进阶",
  expert: "高级",
  Beginner: "入门",
  Advanced: "进阶",
  Expert: "高级",
  "all levels": "全部难度",
};

const reverseCapture = Object.fromEntries(
  Object.entries(captureMessages).map(([english, chinese]) => [
    chinese,
    english,
  ]),
);

function translateCaptured(value: string, locale: Locale) {
  return locale === "zh"
    ? (captureMessages[value] ?? value)
    : (reverseCapture[value] ?? value);
}

function patternTranslation(text: string, locale: Locale) {
  for (const pattern of compiledPatterns) {
    const source = locale === "zh" ? pattern.english : pattern.chinese;
    const match = source.exec(text);
    if (!match) continue;
    const output = locale === "zh" ? pattern.enToZh : pattern.zhToEn;
    const values = match
      .slice(1)
      .map((value) => translateCaptured(value, locale));
    return output.replace(
      /\{(\d+)\}/g,
      (_match, index: string) => values[Number(index)] ?? "",
    );
  }
  return undefined;
}

export function translate(text: string, locale: Locale): string {
  if (locale !== "zh") return text;
  const normalized = text.replace(/\s+/g, " ").trim();
  const translated = Object.hasOwn(chineseMessages, normalized)
    ? chineseMessages[normalized]
    : patternTranslation(normalized, locale);
  if (!translated) return text;
  return `${text.match(/^\s*/)?.[0] ?? ""}${translated}${text.match(/\s*$/)?.[0] ?? ""}`;
}

/** English text for dictionary values, so switching back restores the source. */
function reverseTranslation(text: string): string | undefined {
  if (Object.hasOwn(chineseMessages, text)) return text;
  return Object.entries(chineseMessages).find(
    ([, chinese]) => chinese === text,
  )?.[0];
}

/** undefined means the content needs model translation; known UI copy stays local. */
export function localTranslation(
  text: string,
  locale: Locale,
): string | undefined {
  const normalized = text.replace(/\s+/g, " ").trim();
  if (locale === "en") {
    return (
      reverseTranslation(normalized) ?? patternTranslation(normalized, "en")
    );
  }
  if (Object.hasOwn(chineseMessages, normalized))
    return chineseMessages[normalized];
  if (Object.values(chineseMessages).includes(normalized)) return normalized;
  return patternTranslation(normalized, "zh");
}
